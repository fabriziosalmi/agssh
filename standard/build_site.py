    out.append('<ul class="toc">')
    for fid, ftitle, rows in fams:
        out.append('<li><a href="#%s">%s</a></li>' % (fid.lower(), esc(fid)))
    out.append('</ul>')
    for fid, ftitle, rows in fams:
        out.append('<h3 id="%s">%s — %s</h3>' % (fid.lower(), esc(fid), esc(ftitle)))
        out.append('<div class="tablewrap"><table><thead><tr>'
                   '<th>Rule</th><th>Requirement</th><th>Obl.</th>'
                   '<th>Severity</th><th>Profile</th><th>Levels</th></tr></thead><tbody>')
        for r in rows:
            ob = ('<span class="must">MUST</span>' if r["oblig"] == "MUST"
                  else '<span class="should">SHOULD</span>')
