"""Build the static, CSP-clean website for AGSSH-STD-001 (published at agssh.dev).

The site is a purpose-built WEB surface, distinct from the print PDF: it carries
NO inline <style>/<script> and NO inline style="" attributes, so a strict CSP
(default-src 'none'; style-src 'self'; img-src 'self'; everything else 'none')
holds — which is exactly what lets the page pass agssh's own AG-NET-01 / AG-CSP-02
at Gold. All styling lives in one same-origin stylesheet; all assets are
first-party. The dogfood: the site that publishes the standard conforms to it.

Inputs (already generated by build_pdf.py — run that first):
  ../RULES.md                          the rule table (id/title/oblig/sev/profile/levels)
  ../internal/rules/version_gen.go     the version constant
  AGSSH-STD-001-<ver>.pdf              the rendered standard (copied into the site)

Outputs (into ../site/):
  index.html  agssh-std.css  AGSSH-STD-001-<ver>.pdf  (badge.svg is added by CI)
"""
import os
