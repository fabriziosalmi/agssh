def version():
    vg = open(os.path.join(_root, "internal", "rules", "version_gen.go")).read()
    m = re.search(r'StandardVersion = "([^"]+)"', vg)
    if not m:
        raise SystemExit("build_site: cannot read StandardVersion from version_gen.go")
    return m.group(1)


def parse_rules():
    """Parse RULES.md into [(family_id, family_title, [rows])]; row = dict."""
    md = open(os.path.join(_root, "RULES.md")).read()
    fams, cur = [], None
    for line in md.splitlines():
        # The family heading separator is an em dash today; accept a colon or a
        # hyphen too, so a punctuation change in the generator cannot empty the site.
        h = re.match(r"^## §\S+\s+(AG-[A-Z]+)\s+(?:—|:|-)\s+(.+?)\s*$", line)
        if h:
            cur = (h.group(1), h.group(2), [])
            fams.append(cur)
            continue
        r = re.match(r"^\|\s*`(AG-[A-Z0-9a-z-]+)`\s*\|(.+)$", line)
        if r and cur is not None:
            cells = [c.strip().replace("\\|", "|") for c in r.group(2).split("|")]
            # cells: title, oblig, severity, profile, levels (trailing empty from |)
            title, oblig, sev, prof, levels = (cells + ["", "", "", "", ""])[:5]
            cur[2].append(dict(id=r.group(1), title=title, oblig=oblig,
                               sev=sev, prof=prof, levels=levels))
    if not fams or not all(rows for _, _, rows in fams):
        raise SystemExit("build_site: RULES.md parsed to an empty family; "
                         "refusing to build")
    return fams


def esc(s):
    return html.escape(s, quote=True)


def no_dash(s):
    """Visible copy carries no em dash: ' — ' reads as a colon, a bare one as a comma."""
    return s.replace(" — ", ": ").replace("—", ", ")


